-- ===== 1. ACCOUNTS =====
CREATE TABLE IF NOT EXISTS accounts (
    account_identifier INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name VARCHAR(50) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    email_address VARCHAR(100) NOT NULL,
    role_designation VARCHAR(50) NOT NULL DEFAULT 'ROLE_BORROWER',
    contact_number VARCHAR(20) DEFAULT NULL,
    clerk_user_id VARCHAR(255) DEFAULT NULL,
    password_hash VARCHAR(255) DEFAULT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_attempts INT NOT NULL DEFAULT 0,
    locked_until_timestamp TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
    last_login_timestamp TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
    created_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_accounts_email ON accounts (email_address);

